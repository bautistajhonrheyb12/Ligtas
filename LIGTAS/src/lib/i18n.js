const STORAGE_KEY = 'ligtas-language'

function readLanguage() {
  try {
    return localStorage.getItem(STORAGE_KEY) === 'tl' ? 'tl' : 'en'
  } catch {
    return 'en'
  }
}

export function useLanguage() {
  const [lang, setLang] = useState(readLanguage)

  useEffect(() => {
    try {
      localStorage.setItem(STORAGE_KEY, lang)
    } catch {
      // Language just won't persist between visits.
    }
    document.documentElement.lang = lang === 'tl' ? 'fil' : 'en'
  }, [lang])

  const t = (key, vars) => {
    const value = strings[lang][key] ?? strings.en[key] ?? key
    if (typeof value !== 'string' || !vars) return value
    return value.replace(/\{(\w+)\}/g, (match, name) => vars[name] ?? match)
  }

  return { lang, setLang, t }
}
